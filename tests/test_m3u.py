from collections.abc import Callable
from io import StringIO
from pathlib import Path

import pytest

from genplis.m3u import PlaylistEntry, create_m3u, playlist_entry
from genplis.output import Output, Palette, Theme
from genplis.types import TagValue


def test_extended_header_and_extinf_are_written(tmp_path: Path) -> None:
    playlist_file = tmp_path / "playlist.m3u"

    create_m3u(
        playlist_file,
        [
            PlaylistEntry(
                tmp_path / "song.mp3",
                duration=215.123456,
                title="Motörhead - Ace of Spades",
            )
        ],
    )

    assert playlist_file.read_text(encoding="utf-8") == (
        "#EXTM3U\n#EXTINF:215.123,Motörhead - Ace of Spades\nsong.mp3\n"
    )


def test_plain_mode_writes_only_entries(tmp_path: Path) -> None:
    playlist_file = tmp_path / "playlist.m3u"

    create_m3u(playlist_file, [tmp_path / "song.mp3"], extended=False)

    assert playlist_file.read_text(encoding="utf-8") == "song.mp3\n"


def test_comments_are_written_before_entries(tmp_path: Path) -> None:
    playlist_file = tmp_path / "playlist.m3u"

    create_m3u(
        playlist_file,
        [tmp_path / "song.mp3", tmp_path / "sub" / "other.ogg"],
        comments=[
            'Generated by genplis from "favorites.m3ug"',
            "",
            "# a comment from the source",
            'artist = "Motörhead"',
        ],
        extended=False,
    )

    assert playlist_file.read_text(encoding="utf-8") == (
        '# Generated by genplis from "favorites.m3ug"\n'
        "#\n"
        "# # a comment from the source\n"
        '# artist = "Motörhead"\n'
        "song.mp3\n"
        "sub/other.ogg\n"
    )


def test_extended_header_precedes_comments_and_entries(tmp_path: Path) -> None:
    playlist_file = tmp_path / "playlist.m3u"

    create_m3u(
        playlist_file,
        [tmp_path / "song.mp3"],
        comments=['Generated by genplis from "favorites.m3ug"', "", "genre = Metal"],
    )

    assert playlist_file.read_text(encoding="utf-8") == (
        "#EXTM3U\n"
        '# Generated by genplis from "favorites.m3ug"\n'
        "#\n"
        "# genre = Metal\n"
        "#EXTINF:-1,song\n"
        "song.mp3\n"
    )


def test_extended_m3u_directives_in_comments_are_escaped(tmp_path: Path) -> None:
    playlist_file = tmp_path / "playlist.m3u"

    create_m3u(
        playlist_file,
        [tmp_path / "song.mp3"],
        comments=["#EXTINF:123,Artist"],
    )

    assert playlist_file.read_text(encoding="utf-8") == (
        "#EXTM3U\n# #EXTINF:123,Artist\n#EXTINF:-1,song\nsong.mp3\n"
    )


def test_title_with_comma_is_kept_after_the_first_comma(tmp_path: Path) -> None:
    playlist_file = tmp_path / "playlist.m3u"

    create_m3u(
        playlist_file,
        [
            PlaylistEntry(
                tmp_path / "song.mp3", duration=1.0, title="Artist - Song, Part 2"
            )
        ],
    )

    assert playlist_file.read_text(encoding="utf-8") == (
        "#EXTM3U\n#EXTINF:1.000,Artist - Song, Part 2\nsong.mp3\n"
    )


def test_title_control_characters_are_flattened(tmp_path: Path) -> None:
    playlist_file = tmp_path / "playlist.m3u"

    create_m3u(
        playlist_file,
        [PlaylistEntry(tmp_path / "song.mp3", title="Line\nBreak\r\x00")],
    )

    assert playlist_file.read_text(encoding="utf-8") == (
        "#EXTM3U\n#EXTINF:-1,Line Break\nsong.mp3\n"
    )


@pytest.mark.parametrize(
    ("tags", "expected_title"),
    [
        ({"artist": ["A"], "title": ["T"]}, "A - T"),
        ({"artist": ["A", "B"], "title": ["T"]}, "A - T"),
        ({"title": ["T"]}, "T"),
        ({"artist": ["A"]}, "A"),
        ({"artist": [" "], "title": []}, "song"),
        ({}, "song"),
    ],
)
def test_playlist_entry_title_fallbacks(
    tmp_path: Path, tags: dict[str, list[str]], expected_title: str
) -> None:
    entry = playlist_entry(tmp_path / "song.mp3", tags)

    assert entry.title == expected_title


def test_playlist_entry_uses_duration_and_multi_value_tags(tmp_path: Path) -> None:
    entry = playlist_entry(
        tmp_path / "song.mp3",
        {"artist": ["First", "Second"], "title": ["Track"], "duration": 3.239183},
    )

    assert entry.duration == pytest.approx(3.239183)
    assert entry.title == "First - Track"


@pytest.mark.parametrize(
    ("duration", "expected"),
    [
        (3.239183, 3.239183),
        (4, 4.0),
        ("12.5", 12.5),
        ("not a number", None),
        (None, None),
        (True, None),
        (-1, None),
        (float("inf"), None),
        ([1, 2], None),
    ],
)
def test_playlist_entry_duration_validation(
    tmp_path: Path, duration: TagValue, expected: float | None
) -> None:
    entry = playlist_entry(tmp_path / "song.mp3", {"duration": duration})

    assert entry.duration == expected


def test_cross_drive_entry_falls_back_to_absolute(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    playlist_file = tmp_path / "playlist.m3u"
    entry = tmp_path / "song.mp3"

    def raise_value_error(_self: Path, *_args: object, **_kwargs: object) -> Path:
        raise ValueError("path is on a different drive")

    monkeypatch.setattr(Path, "relative_to", raise_value_error)

    create_m3u(playlist_file, [entry], extended=False)

    assert playlist_file.read_text(encoding="utf-8") == f"{entry}\n"


def test_existing_playlist_is_not_overwritten(tmp_path: Path) -> None:
    playlist_file = tmp_path / "playlist.m3u"
    playlist_file.write_text("keep this\n", encoding="utf-8")

    create_m3u(
        playlist_file,
        [tmp_path / "song.mp3"],
        comments=["ignored"],
        overwrite=False,
    )

    assert playlist_file.read_text(encoding="utf-8") == "keep this\n"


def test_overwrite_warning_color_preserves_plain_output(
    tmp_path: Path,
    strip_ansi: Callable[[str], str],
) -> None:
    playlist_file = tmp_path / "playlist.m3u"
    playlist_file.write_text("keep this\n", encoding="utf-8")

    def run(enabled: bool) -> str:
        stream = StringIO()
        create_m3u(
            playlist_file,
            [tmp_path / "song.mp3"],
            overwrite=False,
            output=Output(
                stream=stream,
                palette=Palette(theme=Theme.DARK, enabled=enabled),
            ),
        )
        return stream.getvalue()

    assert strip_ansi(run(True)) == run(False)
